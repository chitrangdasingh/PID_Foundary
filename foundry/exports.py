"""exports.py - publish the persisted graph: GraphML, Neo4j Cypher, DEXPI-style JSON, asset register (CSV / Excel)."""
import io
import json
import re

import networkx as nx


def load_graph(store, pid_id, version=None, include_rejected=False):
    version = version or store.latest_version(pid_id, "graph_persistence")
    nodes = store.q("SELECT * FROM graph_nodes WHERE pid_id=? AND version=?", (pid_id, version))
    edges = store.q("SELECT * FROM graph_edges WHERE pid_id=? AND version=?", (pid_id, version))
    G = nx.MultiDiGraph(pid_id=pid_id, version=version)
    for n in nodes:
        if n["status"] == "rejected" and not include_rejected:
            continue
        G.add_node(n["node_id"], kind=n["kind"], label=n["label"] or "", cls=n["cls"] or "", sheet=n["sheet_no"] or 0,
                   x=n["x"] or 0.0, y=n["y"] or 0.0, confidence=n["confidence"] or 0.0, status=n["status"] or "")
    for e in edges:
        if e["status"] == "rejected" and not include_rejected:
            continue
        if e["src"] not in G or e["dst"] not in G:
            continue
        a, b = e["src"], e["dst"]
        if e["direction"] and "->" in e["direction"]:
            a, b = e["direction"].split("->")
        G.add_edge(a, b, key=e["edge_id"], kind=e["kind"], direction=e["direction"] or "unknown", confidence=e["confidence"] or 0.0,
                   status=e["status"] or "", evidence=e["evidence"] or "[]")
    return G


def graphml(G):
    buf = io.BytesIO()
    nx.write_graphml(G, buf)
    return buf.getvalue()


def _cy(s):
    return str(s).replace("\\", "\\\\").replace("'", "\\'")


def cypher(G, assets=None):
    out = [f"// P&ID graph {G.graph.get('pid_id')} v{G.graph.get('version')} - generated by PID Foundry. Candidate edges carry status."]
    out.append("CREATE CONSTRAINT IF NOT EXISTS FOR (n:PidNode) REQUIRE n.id IS UNIQUE;")
    for n, d in G.nodes(data=True):
        lab = re.sub(r"[^A-Za-z]", "", d["kind"]) or "Node"
        out.append(f"MERGE (n:PidNode:{lab} {{id:'{_cy(n)}'}}) SET n.tag='{_cy(d['label'])}', n.cls='{_cy(d['cls'])}', n.sheet={d['sheet']}, "
                   f"n.confidence={d['confidence']}, n.status='{_cy(d['status'])}';")
    for a, b, k, d in G.edges(keys=True, data=True):
        rel = {"process": "PROCESS_CONNECTS", "signal": "SIGNAL_TO", "offpage": "CONTINUES_TO"}.get(d["kind"], "CONNECTED_TO")
        out.append(f"MATCH (a:PidNode {{id:'{_cy(a)}'}}), (b:PidNode {{id:'{_cy(b)}'}}) MERGE (a)-[r:{rel} {{id:'{_cy(k)}'}}]->(b) "
                   f"SET r.direction='{_cy(d['direction'])}', r.confidence={d['confidence']}, r.status='{_cy(d['status'])}';")
    for a in assets or []:
        if a["parent_id"]:
            out.append(f"MERGE (p:Asset {{id:'{_cy(a['parent_id'])}'}}) MERGE (c:Asset {{id:'{_cy(a['asset_id'])}'}}) "
                       f"SET c.level='{_cy(a['level'])}', c.tag='{_cy(a['tag'] or '')}', c.name='{_cy(a['name'] or '')}' MERGE (p)-[:HAS_CHILD]->(c);")
    return "\n".join(out)


def dexpi_json(G, source):
    """A DEXPI-shaped JSON view (PlantModel -> Equipment, PipingNetworkSystem, ProcessInstrumentationFunction).
    It is not Proteus XML; it carries the same classes so a converter to DEXPI 1.3 is a mapping exercise."""
    eq, valves, instr, conns = [], [], [], []
    for n, d in G.nodes(data=True):
        item = dict(ID=n, TagName=d["label"], ComponentClass=d["cls"].split("/")[-1], Sheet=d["sheet"], Confidence=d["confidence"], Status=d["status"])
        k = d["kind"]
        (eq if k == "Equipment" else instr if k == "Instrument" else valves if k == "Piping" else conns).append(item)
    segs = [dict(ID=k, FromID=a, ToID=b, Kind=d["kind"], Direction=d["direction"], Confidence=d["confidence"], Status=d["status"])
            for a, b, k, d in G.edges(keys=True, data=True)]
    return dict(PlantModel=dict(PlantInformation=dict(OriginatingSystem="PID Foundry", SourceDrawing=source.get("file_name"),
                                                      DrawingNumber=source.get("drawing_no"), Revision=source.get("revision"), Schema="DEXPI-shaped JSON (1.3 classes)"),
                                Equipment=eq, PipingNetworkSystem=dict(PipingComponents=valves, PipingNetworkSegments=segs),
                                ProcessInstrumentationFunction=instr, OffPageConnectors=conns))


def assets_xlsx(store, pid_id):
    import pandas as pd
    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as xw:
        store.df("SELECT asset_id, parent_id, level, tag, name, asset_class, sheet_no, bom_item, match_status, confidence FROM assets WHERE pid_id=?", (pid_id,)).to_excel(xw, sheet_name="Asset Hierarchy", index=False)
        v = store.latest_version(pid_id, "graph_persistence")
        store.df("SELECT edge_id, src, dst, kind, direction, confidence, status FROM graph_edges WHERE pid_id=? AND version=?", (pid_id, v)).to_excel(xw, sheet_name="Relationships", index=False)
        sv = store.latest_version(pid_id, "symbol_detection")
        store.df("SELECT symbol_id, sheet_no, cls, tag, confidence, method, status, x0, y0, x1, y1 FROM symbols WHERE pid_id=? AND version=?", (pid_id, sv)).to_excel(xw, sheet_name="Detections", index=False)
        rec = store.kv_get(f"recon:{pid_id}", {})
        pd.DataFrame(rec.get("rows", [])).to_excel(xw, sheet_name="BOM Reconciliation", index=False)
    return buf.getvalue()
